#!/usr/bin/env node
/**
 * Copies the backend's business logic (backend/src) into src/mock-api/core so the frontend can run
 * the real API in the browser when NEXT_PUBLIC_DATA_SOURCE=mock (e.g. a frontend-only Vercel demo).
 *
 *   npm run mock:sync          # regenerate src/mock-api/core from ../backend/src
 *   npm run mock:sync -- --check   # exit 1 if the generated copy is out of date (CI)
 *
 * - Node/Express-only files are skipped or replaced by src/mock-api/overrides/<same path>.
 * - Relative ".js" import suffixes (NodeNext) are removed for the bundler.
 * - A few package imports are redirected to browser builds or shims.
 * The output is committed so the frontend builds without the backend folder.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const backendSrc = path.resolve(root, process.env.BACKEND_SRC ?? "../backend/src")
const overridesDir = path.join(root, "src/mock-api/overrides")
const outDir = path.join(root, "src/mock-api/core")
const check = process.argv.includes("--check")

/** Server-only entry points and adapters that the browser runtime never needs. */
const SKIP = new Set([
  "app.ts",
  "server.ts",
  "lib/openapi.ts",
  "middleware/error.ts",
])

const PACKAGE_REWRITES = {
  "csv-parse/sync": "csv-parse/browser/esm/sync",
  "express-rate-limit": "@/mock-api/shims/express-rate-limit",
}

const HEADER = "// AUTO-GENERATED by scripts/sync-mock-core.mjs from backend/src — do not edit. Run `npm run mock:sync`.\n"

function walk(dir, base = dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name)
    if (statSync(full).isDirectory()) return walk(full, base)
    return name.endsWith(".ts") && !name.endsWith(".d.ts") ? [path.relative(base, full)] : []
  })
}

function transform(code) {
  return (
    HEADER +
    code
      .replace(/(from\s+["'])(\.{1,2}\/[^"']+?)\.js(["'])/g, "$1$2$3")
      .replace(/(import\s*\(\s*["'])(\.{1,2}\/[^"']+?)\.js(["']\s*\))/g, "$1$2$3")
      .replace(/(from\s+["'])([^"'.][^"']*)(["'])/g, (m, a, spec, b) => (PACKAGE_REWRITES[spec] ? a + PACKAGE_REWRITES[spec] + b : m))
  )
}

function build() {
  if (!existsSync(backendSrc)) {
    console.error(`Backend source not found at ${backendSrc}. Set BACKEND_SRC or run from the monorepo.`)
    process.exit(1)
  }
  const files = new Map()
  for (const rel of walk(backendSrc)) {
    if (SKIP.has(rel)) continue
    files.set(rel, transform(readFileSync(path.join(backendSrc, rel), "utf8")))
  }
  for (const rel of walk(overridesDir)) {
    files.set(rel, transform(readFileSync(path.join(overridesDir, rel), "utf8")).replace(HEADER, HEADER.replace("from backend/src", "(browser override)")))
  }
  // Every node:/express import must have been replaced.
  for (const [rel, code] of files) {
    const bad = code.match(/from\s+["'](node:[^"']+|express|jsonwebtoken|pino|dotenv[^"']*|helmet|cors|compression)["']/)
    if (bad) {
      console.error(`${rel} imports server-only module "${bad[1]}". Add an override in src/mock-api/overrides/${rel} or skip it.`)
      process.exit(1)
    }
  }
  return files
}

const files = build()

if (check) {
  const current = existsSync(outDir) ? new Set(walk(outDir)) : new Set()
  const stale = [...files].filter(([rel, code]) => !current.has(rel) || readFileSync(path.join(outDir, rel), "utf8") !== code)
  const extra = [...current].filter((rel) => !files.has(rel))
  if (stale.length || extra.length) {
    console.error("src/mock-api/core is out of date with backend/src. Run `npm run mock:sync`.")
    for (const [rel] of stale) console.error(`  changed: ${rel}`)
    for (const rel of extra) console.error(`  removed: ${rel}`)
    process.exit(1)
  }
  console.log(`✔ mock core up to date (${files.size} files)`)
} else {
  rmSync(outDir, { recursive: true, force: true })
  for (const [rel, code] of files) {
    const dest = path.join(outDir, rel)
    mkdirSync(path.dirname(dest), { recursive: true })
    writeFileSync(dest, code)
  }
  console.log(`✔ Synced ${files.size} files from ${path.relative(root, backendSrc)} → ${path.relative(root, outDir)}`)
}
